#!/usr/bin/env node
/* Vendor the umami tracker into public/a.js.

   The page loads its analytics script from its own origin, like every other
   subresource here. That is not a detail: a site whose claim is that nothing
   leaves your machine cannot open by fetching a script from somewhere else, and
   `check-dist.mjs` fails the build on a remote subresource for exactly that
   reason. So the script is a file in this repository, and this tool is how it
   gets there — one that records what it took and from where, so the vendored
   copy can be diffed against upstream rather than trusted.

   The only request the page then makes off its own origin is the tracker's own
   `POST /api/send`, to the host named in `data-host-url` in the page.

       node tools/fetch-tracker.mjs                  # from the analytics host
       node tools/fetch-tracker.mjs --from=https://…  # from somewhere else
       node tools/fetch-tracker.mjs --check          # compare, write nothing

   `--check` exits non-zero when the vendored copy no longer matches what the
   host serves, which is the signal to re-run the tool and read the diff. It is
   not part of `npm run build`: upstream moving is not a reason for a build to fail.

   Ported from stepkeep's `landing/tools/fetch-tracker.mjs`, the same umami.
*/

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'public', 'a.js');

/* The host the page beacons to, which is therefore the host whose script the
   page should carry. It is one hostname of the shared umami; the same file is
   served by every other, so `--from=https://stats.pigmo.app` works while
   TabNow's own hostname does not exist yet. */
const DEFAULT_SOURCE = 'https://stats.tabnow.app';

/* The marker that separates this tool's header from the bytes it copied. It has
   to be a *closed* comment: written as a bare opening, it swallows the whole
   tracker, the file stops parsing, and every visit goes uncounted in silence.
   That is why the result is parsed before it is written, below. */
const BEGIN = '/* --- vendored file begins --- */';

function arg(name, fallback) {
  const hit = process.argv.slice(2).find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
}

const source = arg('from', DEFAULT_SOURCE).replace(/\/$/, '');
const url = `${source}/script.js`;
const check = process.argv.includes('--check');

const response = await fetch(url);
if (!response.ok) {
  console.error(`fetch-tracker: ${url} answered ${response.status}`);
  process.exit(1);
}
const body = await response.text();
const digest = createHash('sha256').update(body).digest('hex');

const header = [
  '/* umami tracker, vendored.',
  '',
  '   Generated by tools/fetch-tracker.mjs. Do not edit: re-run the tool.',
  '',
  `     source         ${url}`,
  `     last-modified  ${response.headers.get('last-modified') ?? 'unstated'}`,
  `     sha256         ${digest}`,
  `     vendored       ${new Date().toISOString().slice(0, 10)}`,
  '',
  '   What it does, read out of this file rather than recalled: it reads its',
  '   settings from the data- attributes on its own script tag, posts a pageview',
  '   to <data-host-url>/api/send, sets no cookie, and touches localStorage only',
  '   to read the `umami.disabled` opt-out, inside a try/catch. Nothing else is',
  '   stored on the visitor\'s device, which is what lets the privacy page say',
  '   there is no banner to click.',
  '*/',
  BEGIN,
  '',
].join('\n');

const next = `${header}${body}${body.endsWith('\n') ? '' : '\n'}`;

/* A syntax error in the vendored file is the quietest failure this site can
   have. It still loads, the script that would have complained never runs, no
   check here reads JavaScript, and the only symptom is that no visit is ever
   counted. So it is parsed before it is written — or before --check is allowed
   to call it a match. */
try {
  new vm.Script(next);
} catch (error) {
  console.error(`fetch-tracker: the vendored script does not parse — ${error.message}`);
  process.exit(1);
}

if (check) {
  let current = null;
  try { current = await readFile(OUT, 'utf8'); } catch {}
  const strip = (text) => (text ?? '').slice(text?.indexOf(BEGIN) + BEGIN.length);
  if (current !== null && strip(current) === strip(next)) {
    console.log(`fetch-tracker: public/a.js matches ${url}`);
    process.exit(0);
  }
  console.error(`fetch-tracker: public/a.js differs from ${url} — re-run without --check and read the diff`);
  process.exit(1);
}

await writeFile(OUT, next);
console.log(`fetch-tracker: wrote public/a.js from ${url} (${body.length} bytes, sha256 ${digest.slice(0, 16)}…)`);
